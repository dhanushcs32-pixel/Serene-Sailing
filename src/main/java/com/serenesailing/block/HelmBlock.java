/**
 * Ship's Wheel (Helm) steering station. Right-click turns starboard (+15 deg),
 * sneak + right-click turns port (-15 deg), clamped to [-30, +30]. The angle
 * lives in {@link HelmBlockEntity} and is propagated to all attached rudders
 * by {@code ServerPhysicsHandler}.
 */
public class HelmBlock extends Block implements EntityBlock, SimpleWaterloggedBlock {

    public static final DirectionProperty FACING = HorizontalDirectionalBlock.FACING;
    public static final BooleanProperty WATERLOGGED = BlockStateProperties.WATERLOGGED;

    /** Combined pedestal + wheel footprint (model wheel extends to y=20, clipped at 16). */
    protected static final VoxelShape SHAPE = Block.box(1.0, 0.0, 4.0, 15.0, 16.0, 10.0);

    public HelmBlock(BlockBehaviour.Properties properties) {
        super(properties);
        this.registerDefaultState(this.stateDefinition.any()
                .setValue(FACING, Direction.NORTH)
                .setValue(WATERLOGGED, false));
    }

    @Override
    public VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return SHAPE;
    }

    @Nullable
    @Override
    public BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new HelmBlockEntity(pos, state);
    }

    /**
     * Opens the Ship's Wheel slider GUI instead of the old +/-15 degree click
     * stepping. The slider writes the authoritative angle back through
     * {@code SetHelmAnglePayload}; the block entity's update packet keeps all
     * other clients in sync.
     */
    @Override
    protected InteractionResult useWithoutItem(BlockState state, Level level, BlockPos pos, Player player, BlockHitResult hitResult) {
        if (level.isClientSide
                && level.getBlockEntity(pos) instanceof HelmBlockEntity helm) {
            HelmScreenOpener.open(pos, helm.getSteeringAngle());
        }
        return InteractionResult.SUCCESS;
    }

    @Override
    protected ItemInteractionResult useItemOn(ItemStack stack, BlockState state, Level level, BlockPos pos, Player player, InteractionHand hand, BlockHitResult hitResult) {
        if (level.isClientSide
                && level.getBlockEntity(pos) instanceof HelmBlockEntity helm) {
            HelmScreenOpener.open(pos, helm.getSteeringAngle());
        }
        return ItemInteractionResult.sidedSuccess(level.isClientSide);
    }

    @Override
    public BlockState getStateForPlacement(BlockPlaceContext context) {
        FluidState fluidState = context.getLevel().getFluidState(context.getClickedPos());
        return this.defaultBlockState()
                .setValue(FACING, context.getHorizontalDirection().getOpposite())
                .setValue(WATERLOGGED, fluidState.getType() == Fluids.WATER);
    }

    @Override
    public FluidState getFluidState(BlockState state) {
        return state.getValue(WATERLOGGED) ? Fluids.WATER.getSource(false) : super.getFluidState(state);
    }

    @Override
    public BlockState updateShape(BlockState state, Direction direction, BlockState neighborState, LevelAccessor level, BlockPos pos, BlockPos neighborPos) {
        if (state.getValue(WATERLOGGED)) {
            level.scheduleTick(pos, Fluids.WATER, Fluids.WATER.getTickDelay(level));
        }
        return super.updateShape(state, direction, neighborState, level, pos, neighborPos);
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING, WATERLOGGED);
    }
}
