package com.serenesailing.physics;

import org.joml.Vector3d;
import org.joml.Vector3dc;

public final class RudderHydrodynamics {

    private static final double WATER_DENSITY = 1000.0; // kg/m^3
    private static final double RUDDER_SURFACE_AREA = 1.5; // m^2
    private static final double LIFT_COEFFICIENT_SLOPE = 2.0;

    private RudderHydrodynamics() {}

    /**
     * Calculates the hydrodynamic steering force and resulting torque on the hull.
     *
     * @param shipLinearVel     Ship linear velocity in world space (m/s)
     * @param shipAngularVel    Ship angular velocity (rad/s)
     * @param shipForwardDir    Ship forward direction unit vector
     * @param rudderOffsetFromCoM Offset vector from ship Center of Mass to rudder
     * @param steeringAngleDeg  Rudder deflection angle in degrees [-45, +45]
     * @return Result containing steering force and yaw torque
     */
    public static RudderForceResult calculateRudderForces(
            Vector3d shipLinearVel,
            Vector3d shipAngularVel,
            Vector3d shipForwardDir,
            Vector3d rudderOffsetFromCoM,
            float steeringAngleDeg
    ) {
        if (Math.abs(steeringAngleDeg) < 0.5f) {
            return new RudderForceResult(new Vector3d(0, 0, 0), new Vector3d(0, 0, 0));
        }

        // Flow velocity at the rudder = -(LinearVel + AngularVel x RudderOffset)
        Vector3d rotationalVelocity = new Vector3d(shipAngularVel).cross(rudderOffsetFromCoM);
        Vector3d totalRudderVel = new Vector3d(shipLinearVel).add(rotationalVelocity);

        // Forward speed through water
        double forwardSpeed = totalRudderVel.dot(shipForwardDir);

        // Deadband on the TOTAL inflow speed: below 0.05 m/s any "flow" is
        // numerical noise (angular-velocity rounding near standstill), which
        // would otherwise produce rapidly alternating torque - the stationary
        // rudder jitter. Zero force eliminates it.
        if (totalRudderVel.length() < 0.05) {
            return new RudderForceResult(new Vector3d(0, 0, 0), new Vector3d(0, 0, 0));
        }

        // Port/Starboard unit vector
        Vector3d starboardDir = new Vector3d(shipForwardDir).cross(0, 1, 0).normalize();

        double deflectionRad = Math.toRadians(steeringAngleDeg);
        // Soft direction factor instead of a hard Math.signum: ramps smoothly
        // through zero over +/-0.5 m/s so flow reversal cannot flip the torque
        // direction in a single physics step (secondary jitter source).
        double directionFactor = Math.max(-1.0, Math.min(1.0, forwardSpeed / 0.5));
        double angleOfAttack = -deflectionRad * directionFactor;

        // Lateral lift generated by rudder foil
        double dynamicPressure = 0.5 * WATER_DENSITY * forwardSpeed * forwardSpeed;
        double liftMagnitude = dynamicPressure * RUDDER_SURFACE_AREA * (LIFT_COEFFICIENT_SLOPE * Math.sin(angleOfAttack));

        Vector3d steeringForce = new Vector3d(starboardDir).mul(liftMagnitude);

        // Torque = r x F
        Vector3d steeringTorque = new Vector3d(rudderOffsetFromCoM).cross(steeringForce);

        return new RudderForceResult(steeringForce, steeringTorque);
    }

    public record RudderForceResult(Vector3d force, Vector3d torque) {}

    /** Maximum effective angle of attack before stall, in degrees. */
    private static final double MAX_AOA_DEG = 45.0;

    /**
     * Local-frame rudder model used by the live physics bridge.
     *
     * <p>All vectors are in <b>sub-level local coordinates</b> (bow = -Z).
     * Inflow is the negative of the ship's planar velocity:
     * {@code V_inflow = -V_local_planar}. The effective inflow angle is
     * {@code beta = atan2(V_inflow.x, V_inflow.z)}, and the angle of attack is
     * {@code alpha = clamp(theta_rudder - beta, +-45 deg)}. Lift acts strictly
     * perpendicular to the inflow on the X/Z plane; drag acts anti-parallel.</p>
     *
     * @param shipLocalPlanarVel ship velocity expressed in sub-level local frame
     * @param steeringAngleDeg   rudder deflection [-30, +30] degrees
     * @param facingSign         +1 if the rudder block faces the stern (aft, correct
     *                           mounting), -1 if mounted backwards - inverts its
     *                           deflection so backwards-placed rudders don't steer
     *                           the wrong way
     * @return hydrodynamic force in Newtons, sub-level local frame
     */
    public static Vector3d calculateLocalRudderForce(Vector3dc shipLocalPlanarVel,
                                                     float steeringAngleDeg,
                                                     float facingSign) {
        // V_inflow = -V_ship, X/Z plane only.
        Vector3d inflow = new Vector3d(-shipLocalPlanarVel.x(), 0.0, -shipLocalPlanarVel.z());
        double inflowSpeed = inflow.length();

        // Stationary deadband: below this the "flow" is numerical noise.
        if (inflowSpeed < 0.05) {
            return new Vector3d(0, 0, 0);
        }

        Vector3d inflowDir = inflow.normalize();
        double beta = Math.atan2(inflow.x, inflow.z);
        double theta = Math.toRadians(
                Math.max(-MAX_AOA_DEG, Math.min(MAX_AOA_DEG, steeringAngleDeg)));
        // Account for how the player mounted the rudder block: a blade facing
        // forward instead of aft deflects opposite to the helm order.
        theta *= facingSign;
        double alpha = Math.max(-Math.toRadians(MAX_AOA_DEG),
                Math.min(Math.toRadians(MAX_AOA_DEG), theta - beta));

        // Foil coefficients: linear lift slope with stall at |alpha| = 45 deg,
        // plus a small parasitic-drag baseline.
        double cl = 2.0 * Math.sin(2.0 * alpha);
        double cd = 1.5 * Math.sin(alpha) * Math.sin(alpha) + 0.05;

        double q = 0.5 * WATER_DENSITY * inflowSpeed * inflowSpeed;

        // Lift: perpendicular to inflow on the X/Z plane. Rotating the inflow
        // direction by -90 degrees gives (dirZ, -dirX) negated -> (-dirZ, dirX),
        // which pushes the stern to port for positive alpha => bow turns starboard.
        double liftMag = q * RUDDER_SURFACE_AREA * cl;
        double dragMag = q * RUDDER_SURFACE_AREA * cd;

        return new Vector3d(
                -inflowDir.z * liftMag - inflowDir.x * dragMag,
                0.0,
                inflowDir.x * liftMag - inflowDir.z * dragMag);
    }
}